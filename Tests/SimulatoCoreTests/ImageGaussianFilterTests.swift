    @Test func filteredValuesMatchAbTEM() throws {
        for (name, sx, sy, boundary, want) in Self.pinned {
            let f = try Self.image.gaussianFiltered(sigmaX: sx, sigmaY: sy, boundary: boundary)
            #expect(f.nx == 7 && f.ny == 9 && f.samplingX == 0.3 && f.samplingY == 0.25, "\(name) shape")
            #expect(Self.close(f.values, want), "\(name)")
        }
    }

    @Test func zeroSigmaLeavesTheImageAndAPeriodicFilterKeepsTheSum() throws {
        #expect(try Self.image.gaussianFiltered(sigmaX: 0, sigmaY: 0) == Self.image)
        let f = try Self.image.gaussianFiltered(sigmaX: 0.7, sigmaY: 1.1)
        let before = Self.image.values.reduce(0, +), after = f.values.reduce(0, +)
        #expect(abs(after - before) <= 1e-12 * abs(before), "a normalised kernel on a periodic image keeps the total")
        let flat = RealField.unchecked(nx: 4, ny: 5, values: [Double](repeating: 3, count: 20), samplingX: 0.2, samplingY: 0.2)
        for b in [RealField.FilterBoundary.periodic, .reflect] {
            #expect(try flat.gaussianFiltered(sigmaX: 0.5, sigmaY: 0.5, boundary: b).values.allSatisfy { abs($0 - 3) <= 1e-14 })
        }
    }

    @Test func refusesABadSigma() {
        let bad: [(Double, Double)] = [(-0.1, 0.2), (0.2, -1), (.nan, 0.1), (0.1, .infinity), (1e30, 0)]
        for (x, y) in bad {
            #expect(throws: ImageOperationError.self) {
                _ = try Self.image.gaussianFiltered(sigmaX: x, sigmaY: y)
            }
        }
        #expect(throws: ImageOperationError.self) { _ = try Self.image.gaussianFiltered(sigmaX: 1, sigmaY: 1, boundary: .constant(.nan)) }
    }
